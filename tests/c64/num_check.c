/* Three-way compare, zero tests. */
static void cmp_zero(void) {
    num_t a, b, z, nz;
    num_from_int(&a, 2); num_from_int(&b, 3);
    CHECK(num_cmp(&a, &b) < 0); CHECK(num_cmp(&b, &a) > 0); CHECK_EQ_INT(num_cmp(&b, &b), 0);
    num_from_int(&a, -2); CHECK(num_cmp(&a, &b) < 0); CHECK(num_cmp(&b, &a) > 0);
    num_from_int(&b, -3); CHECK(num_cmp(&a, &b) > 0);
    num_from_int(&z, 0); num_neg(&nz, &z);
    CHECK(num_is_zero(&z)); CHECK(num_is_zero(&nz)); CHECK_EQ_INT(num_cmp(&z, &nz), 0);
    CHECK(num_cmp(&a, &z) < 0); CHECK(num_cmp(&z, &a) > 0); CHECK(num_cmp(&nz, &a) > 0);
    num_from_int(&a, 2); CHECK(num_cmp(&a, &nz) > 0); CHECK(num_cmp(&nz, &a) < 0);
    P(&a, "1.0000001"); num_from_int(&b, 1); CHECK(num_cmp(&a, &b) > 0); CHECK(!num_is_zero(&a));
    P(&a, "1e-38"); CHECK(!num_is_zero(&a)); CHECK(num_cmp(&a, &z) > 0);
}

/* A chain like real VM use: 40 rounds of 13 mixed operations (520 ops),
 * results computed in place. Every op must return 0. */
static void chain(void) {
    num_t i, sq, r, sum, half, one, t, u, eps, acc;
    unsigned char n, bad = 0, off = 0;
    num_from_int(&sum, 0); P(&half, "0.5"); num_from_int(&one, 1); P(&eps, "1e-6");
    num_from_int(&acc, 1);
    for (n = 1; n <= 40; ++n) {
        num_from_int(&i, n);
        bad |= num_mul(&sq, &i, &i);                 /* n^2, exact */
        bad |= num_fn(NUMFN_SQR, &r, &sq);           /* ~n */
        bad |= num_add(&r, &r, &half);
        bad |= num_fn(NUMFN_INT, &r, &r);            /* round -> n */
        bad |= num_add(&sum, &sum, &r);
        bad |= num_fn(NUMFN_SIN, &t, &i); bad |= num_mul(&t, &t, &t);
        bad |= num_fn(NUMFN_COS, &u, &i); bad |= num_mul(&u, &u, &u);
        bad |= num_add(&t, &t, &u);                  /* sin^2 + cos^2 */
        bad |= num_sub(&t, &t, &one);
        bad |= num_fn(NUMFN_ABS, &t, &t);
        if (num_cmp(&t, &eps) > 0) ++off;
        bad |= num_mul(&acc, &acc, &i);              /* acc *= n ... */
        if (n <= 33) bad |= num_div(&acc, &acc, &i); /* ... undone up to 33 */
    }
    CHECK_EQ_INT(bad, 0); CHECK_EQ_INT(off, 0);
    fmt_is(&sum, "820");
    fmt_is(&acc, "9.39635424E+10");                  /* 34*35*...*40, exact */
}

/* num_parse gives the nearest C64 value (round half to even), checked on
 * the packed bytes (expected bytes computed with exact rationals), and
 * literals of up to 9 significant digits print back unchanged. */
static void bytes_at(unsigned line, const char *s, uint8_t b0, uint8_t b1, uint8_t b2, uint8_t b3, uint8_t b4)
{
    num_t a;
    if (num_parse(s, &a) != 0 || a.b[0] != b0 || a.b[1] != b1 || a.b[2] != b2 || a.b[3] != b3 || a.b[4] != b4) {
        ++failures;
        printf(" line %u %s: %02x %02x %02x %02x %02x\n", line, s, a.b[0], a.b[1], a.b[2], a.b[3], a.b[4]);
    }
}
#define BYTES(s, b0, b1, b2, b3, b4) bytes_at(__LINE__, s, b0, b1, b2, b3, b4)
static void round_trip(unsigned line, const char *s, const char *want)
{
    num_t a;
    if (num_parse(s, &a) != 0) { ++failures; printf(" line %u parse %s\n", line, s); return; }
    fmt_at(line, &a, want);
}
#define RT(s) round_trip(__LINE__, s, s)
static void parse_exact(void) {
    BYTES("3.14159265358979", 0x82, 0x49, 0x0F, 0xDA, 0xA2);
    BYTES("0.1", 0x7D, 0x4C, 0xCC, 0xCC, 0xCD);
    BYTES("0.0001", 0x73, 0x51, 0xB7, 0x17, 0x59);
    BYTES("1.7e38", 0xFF, 0x7F, 0xC9, 0x9E, 0x3C);
    BYTES("0.000099", 0x73, 0x4F, 0x9E, 0x38, 0x65);
    BYTES("-1e-38", 0x02, 0xD9, 0xC7, 0xDC, 0xED);
    BYTES("-1.70141183e38", 0xFF, 0xFF, 0xFF, 0xFF, 0xF4);
    BYTES("1", 0x81, 0x00, 0x00, 0x00, 0x00);
    BYTES("1e-50", 0x00, 0x00, 0x00, 0x00, 0x00);        /* underflow -> 0 */
    RT("3.14159"); RT("2.71828"); RT("1.41421356"); RT("0.123456789");
    RT("123.456"); RT("0.1"); RT("99.99"); RT("0.7"); RT("12345.6789");
    RT("0.000123"); RT("987654321"); RT("0.5");
    round_trip(__LINE__, "0.000099", "9.9E-05");
    round_trip(__LINE__, "6.02214076e23", "6.02214076E+23");
    round_trip(__LINE__, "1.60217663e-19", "1.60217663E-19");
    round_trip(__LINE__, "0000012.5000", "12.5");
}

/* Generated vectors (tools/gen_num_vectors.py): random packed values in
 * every exponent range must print exactly as the host num_format prints the
 * same value; random literals must parse to the exactly rounded C64 value
 * and, with up to 9 significant digits, print as the host prints them. */
static void vectors(void) {
    num_t a;
    unsigned k;
    char b[16];
    for (k = 0; k < sizeof fmt_vecs / sizeof fmt_vecs[0]; ++k) {
        memcpy(a.b, fmt_vecs[k].b, 5);
        num_format(&a, b);
        if (strcmp(b, fmt_vecs[k].s) != 0) {
            ++failures;
            printf(" fmt %u got %s\n", k, b);
        }
    }
    for (k = 0; k < sizeof parse_vecs / sizeof parse_vecs[0]; ++k) {
        memset(a.b, 0xEE, 5);
        if (num_parse(parse_vecs[k].lit, &a) != 0 || memcmp(a.b, parse_vecs[k].b, 5) != 0) {
            ++failures;
            printf(" parse %u: %02x %02x %02x %02x %02x\n", k, a.b[0], a.b[1], a.b[2], a.b[3], a.b[4]);
        } else if (parse_vecs[k].s) {
            num_format(&a, b);
            if (strcmp(b, parse_vecs[k].s) != 0) {
                ++failures;
                printf(" rt %u got %s\n", k, b);
            }
        }
    }
}

static void group(const char *name, void (*f)(void))
{
    unsigned before = failures;
    f();
    if (failures == before) printf("%s ok\n", name);
    else printf("%s: %u bad\n", name, failures - before);
}

