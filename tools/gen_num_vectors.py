#!/usr/bin/env python3
"""Generate tests/c64/num_vectors.h: random test vectors for the C64 number
layer, with expected results from the HOST implementation.

usage: tools/gen_num_vectors.py [OUT]     (default tests/c64/num_vectors.h)

- FMT: random packed C64 floats (every exponent range, both signs, plus
  boundary values). The expected string is what src/host/num_host.c's
  num_format prints for the same value as a double (every C64 value is
  exactly representable as a double): a small host program is compiled
  from num_host.c and run on the values.
- PARSE: random decimal literals (lexer style "ddd.ddd" and with exponents).
  The expected bytes are the exactly rounded (half to even) C64 value,
  computed here with rationals; for literals of at most 9 significant
  digits the expected string is again the host's num_format of strtod().
Deterministic (fixed seed); rerun after changing the rules.
"""
import os
import random
import subprocess
import sys
import tempfile
from fractions import Fraction

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def value(b):
    """Exact value of a packed C64 float as a Fraction."""
    if b[0] == 0:
        return Fraction(0)
    m = ((b[1] | 0x80) << 24) | (b[2] << 16) | (b[3] << 8) | b[4]
    v = Fraction(m) * Fraction(2) ** (b[0] - 0xA0)
    return -v if b[1] & 0x80 else v


def pack(v):
    """Nearest C64 float (round half to even); None on overflow."""
    if v == 0:
        return [0] * 5
    neg = v < 0
    v = abs(v)
    e = 0
    while v >= 2 ** 32: v /= 2; e += 1
    while v < 2 ** 31: v *= 2; e -= 1
    m = int(v); fr = v - m
    if fr > Fraction(1, 2) or (fr == Fraction(1, 2) and m & 1):
        m += 1
        if m == 2 ** 32: m = 2 ** 31; e += 1
    ex = 0x80 + e + 32
    if ex > 255: return None
    if ex < 1: return [0] * 5
    return [ex, ((m >> 24) & 0x7F) | (0x80 if neg else 0), (m >> 16) & 255, (m >> 8) & 255, m & 255]


def host_format(doubles_hex):
    """Run the host num_format on doubles given as C hex-float literals."""
    src = ['#include "platform/num.h"', '#include <stdio.h>',
           'static const double v[] = {' + ','.join(doubles_hex) + '};',
           'int main(void){char b[16];unsigned i;for(i=0;i<sizeof v/sizeof v[0];i++)'
           '{num_t a=v[i];num_format(&a,b);puts(b);}return 0;}']
    with tempfile.TemporaryDirectory() as d:
        c = os.path.join(d, "h.c"); x = os.path.join(d, "h")
        open(c, "w").write("\n".join(src) + "\n")
        subprocess.run(["cc", "-std=c99", "-O1", "-I", os.path.join(ROOT, "src"), "-o", x, c,
                        os.path.join(ROOT, "src/host/num_host.c"), "-lm"], check=True)
        return subprocess.run([x], check=True, capture_output=True, text=True).stdout.split("\n")[:len(doubles_hex)]


def hexd(fr):
    return float(fr).hex()   # exact: C64 values have 32-bit mantissas


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "tests/c64/num_vectors.h")
    rnd = random.Random(20261115)
    fmt = []
    for _ in range(160):
        e = rnd.choice([rnd.randrange(1, 256), rnd.randrange(0x70, 0xA2)])
        fmt.append([e] + [rnd.randrange(256) for _ in range(4)])
    # boundaries: around 1e-4, 1e9, ties, extremes
    for v in [Fraction(1, 10 ** 4), Fraction(10 ** 9), Fraction(999999999), Fraction(1999999999, 2),
              Fraction(246913577, 2), Fraction(246913579, 2), Fraction(2 ** 32 - 1), Fraction(1, 3)]:
        fmt.append(pack(v))
    fmt += [[0x73, 0x51, 0xB7, 0x17, 0x58], [0x73, 0xD1, 0xB7, 0x17, 0x5A], [0x01, 0x00, 0, 0, 0],
            [0x01, 0xFF, 0xFF, 0xFF, 0xFF], [0xFF, 0x7F, 0xFF, 0xFF, 0xFF], [0xFF, 0x80, 0, 0, 0]]
    fstr = host_format([hexd(value(b)) for b in fmt])

    lits = []
    for _ in range(70):
        ip = str(rnd.randrange(0, 10 ** rnd.randrange(1, 8)))
        fp = "".join(rnd.choice("0123456789") for _ in range(rnd.randrange(0, 16 - len(ip))))
        lits.append(ip + ("." + fp if fp else ""))
    for _ in range(30):
        mant = str(rnd.randrange(1, 10 ** rnd.randrange(1, 10)))
        if rnd.random() < 0.5 and len(mant) > 1: mant = mant[0] + "." + mant[1:]
        lits.append(mant + "e" + str(rnd.randrange(-40, 39)))
    lits += ["0.000099", "3.14159265358979", "4294967295", "4294967296", "0.30000000000000004"]
    parse = []
    for s in lits:
        b = pack(Fraction(s))
        if b is None:
            continue
        parse.append((s, b))
    sig = lambda s: len(s.split("e")[0].replace(".", "").lstrip("0").rstrip("0") or "0")
    # literals with <= 9 significant digits must print as the host prints them
    rt = [(s, b) for s, b in parse if sig(s) <= 9]
    rstr = host_format([float(Fraction(s)).hex() for s, _ in rt])

    L = ["/* Generated by tools/gen_num_vectors.py -- do not edit. Expected",
         " * strings come from the host num_format (src/host/num_host.c). */",
         "typedef struct { uint8_t b[5]; const char *s; } fmt_vec;",
         "typedef struct { const char *lit; uint8_t b[5]; const char *s; } parse_vec;",
         "static const fmt_vec fmt_vecs[] = {"]
    for b, s in zip(fmt, fstr):
        L.append("    { { 0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X }, \"%s\" }," % (*b, s))
    L.append("};")
    L.append("static const parse_vec parse_vecs[] = {")
    rmap = dict(zip([s for s, _ in rt], rstr))
    for s, b in parse:
        L.append("    { \"%s\", { 0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X }, %s }," %
                 (s, *b, '"%s"' % rmap[s] if s in rmap else "0"))
    L.append("};")
    open(out, "w").write("\n".join(L) + "\n")
    print(f"{out}: {len(fmt)} format vectors, {len(parse)} parse vectors ({len(rt)} round-trip)")


if __name__ == "__main__":
    main()
