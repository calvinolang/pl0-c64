#!/usr/bin/env python3
"""Embed a PL/0 source file in a C header for the C64 check programs.

usage: pl0_to_c.py SOURCE.pl0 OUT.h [--drawing]

Writes
    #define CORE_SRC_NAME "<base name>"
    #define CORE_SRC_DRAWING 0|1
    static const unsigned char core_src[] = { 0x7b, ..., 0x00 };
The bytes are the file's bytes verbatim (ASCII, the program's internal
encoding), NUL-terminated, written as numbers so no compiler charmap can
touch them. The file must be plain ASCII (bytes 0x0A and 0x20-0x7E) and
shorter than 8192 bytes (MAX_SOURCE, the C64 source buffer holds the NUL).
"""
import os
import sys


def main(argv):
    if len(argv) not in (3, 4) or (len(argv) == 4 and argv[3] != "--drawing"):
        sys.exit(__doc__)
    src, out = argv[1], argv[2]
    data = open(src, "rb").read()
    bad = [b for b in data if b != 0x0A and not 0x20 <= b <= 0x7E]
    if bad:
        sys.exit("pl0_to_c: %s is not plain ASCII (byte 0x%02X)" % (src, bad[0]))
    if len(data) >= 8192:
        sys.exit("pl0_to_c: %s has %d bytes, the limit is 8191" % (src, len(data)))
    name = os.path.splitext(os.path.basename(src))[0]
    rows = []
    blob = list(data) + [0]
    for i in range(0, len(blob), 12):
        rows.append("    " + ", ".join("0x%02x" % b for b in blob[i:i + 12]) + ",")
    with open(out, "w") as f:
        f.write("/* Generated by tools/pl0_to_c.py from %s -- do not edit. */\n" % src)
        f.write('#define CORE_SRC_NAME "%s"\n' % name)
        f.write("#define CORE_SRC_DRAWING %d\n" % (1 if len(argv) == 4 else 0))
        f.write("static const unsigned char core_src[] = {\n%s\n};\n" % "\n".join(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
