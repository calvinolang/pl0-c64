#!/usr/bin/env python3
"""Rules every built-in example must follow (called by tests/run_examples.sh).

Usage:
  example_rules.py source FILE.pl0
      name: lowercase [a-z0-9], base name <= 12 chars; plain ASCII;
      <= 1000 bytes; every line <= 38 chars (C64 editor, 40 columns);
      line 1 is "{ description }" with 1..24 chars between the braces
      (the picker shows NAME plus this text); at least one more comment
      line follows it (a short explanation for beginners).
  example_rules.py output text|drawing STDOUT LINES
      text: no line drawn; output lines <= 39 chars and <= 22 lines (it
      must fit the 40x25 run screen without wrapping or scrolling away).
      drawing: something drawn, and nothing clipped: no recorded endpoint
      on the screen border (the dump is in pixels: x 0/319, y 0/199;
      turtle x -160/159, y 99/-100), so the figure fits the screen.
  example_rules.py budget check|write ROWS.tsv DOC.md
      ROWS.tsv: name kind bytes instructions functions turtle-trig lines
      xmin xmax ymin ymax.
      write: (re)generate DOC.md; check: fail if DOC.md differs.
Exit 0 ok, 1 rule broken (each problem printed), 2 usage.
"""
import os
import re
import sys

MAX_BYTES = 1000
MAX_LINE = 38
MAX_DESC = 24
MAX_NAME = 12
MAX_OUT_COLS = 39
MAX_OUT_LINES = 22
INSTR_BUDGET = 40000


def check_source(path):
    problems = []
    base = os.path.basename(path)
    stem, ext = os.path.splitext(base)
    if ext != ".pl0" or not re.fullmatch(r"[a-z][a-z0-9]{0,%d}" % (MAX_NAME - 1), stem):
        problems.append("file name must be lowercase [a-z0-9], <= %d chars, .pl0" % MAX_NAME)
    with open(path, "rb") as f:
        data = f.read()
    if len(data) > MAX_BYTES:
        problems.append("%d bytes, more than %d" % (len(data), MAX_BYTES))
    if any(b > 126 or (b < 32 and b not in (10,)) for b in data):
        problems.append("not plain ASCII (or contains tabs/CR)")
    lines = data.decode("ascii", "replace").split("\n")
    for i, line in enumerate(lines, 1):
        if len(line) > MAX_LINE:
            problems.append("line %d has %d chars, more than %d" % (i, len(line), MAX_LINE))
        if line != line.rstrip():
            problems.append("line %d has trailing blanks" % i)
    m = re.fullmatch(r"\{([^{}]*)\}", lines[0]) if lines else None
    if not m or not m.group(1).strip():
        problems.append("line 1 must be a one-line comment { description }")
    elif len(m.group(1).strip()) > MAX_DESC:
        problems.append("description has %d chars, more than %d" % (len(m.group(1).strip()), MAX_DESC))
    if len(lines) < 2 or not lines[1].startswith("{"):
        problems.append("line 2 must start a comment explaining the program")
    return problems


def read_lines(path):
    with open(path) as f:
        return [tuple(int(v) for v in l.split()) for l in f if l.strip()]


def check_output(kind, out_path, lines_path):
    problems = []
    segs = read_lines(lines_path)
    if kind == "text":
        if segs:
            problems.append("a text example must not draw")
        with open(out_path) as f:
            out = f.read().split("\n")
        if out and out[-1] == "":
            out.pop()
        if len(out) > MAX_OUT_LINES:
            problems.append("%d output lines, more than %d" % (len(out), MAX_OUT_LINES))
        for i, line in enumerate(out, 1):
            if len(line) > MAX_OUT_COLS:
                problems.append("output line %d has %d chars, more than %d" % (i, len(line), MAX_OUT_COLS))
    elif kind == "drawing":
        if not segs:
            problems.append("a drawing example must draw")
        for s in segs:
            if any(x in (0, 319) for x in s[0::2]) or any(y in (0, 199) for y in s[1::2]):
                problems.append("line %s touches the screen border (clipped?)" % (s,))
                break
    else:
        problems.append("unknown kind " + kind)
    return problems


DOC_HEAD = """# Example budget

Generated by `tests/run_examples.sh --write-budget`; `make test` fails when
this table is out of date. Every built-in example must stay under
**{budget:,} executed P-code instructions** (`pl0host --count-instr`): the
Task 1 spike measured 0.5-1.3 ms per instruction on the C64, so that is
roughly 30 s. Drawings cost more per instruction (a `turn` recomputes sin
and cos, about 56 ms; every line is plotted), so their counts are kept lower.
Source limit: 1000 bytes; lines at most 38 characters.

"Functions" counts the math function calls among the instructions and
"Turn trig" the sin and cos evaluations caused by `turn` (ROM sin is about
28 ms, sqrt about 53 ms, so these dominate drawing time on the C64).
"Lines" is the number of line segments drawn (host recorder, after
clipping); "Extent" is the bounding box of the drawing in pixel
coordinates as the recorder dumps them (screen: x 0..319, y 0..199 from
the top; the turtle's x -160..159, y 99..-100).
"C64 s" is the time from F1 to the end of the program on a PAL C64 in
VICE: `pl0_compile` plus `pl0_run` (CPU cycles from the CIA2 timers /
985248), recorded by
`tests/c64_examples.sh --record` in `c64-times.tsv` next to this file
(`make c64-examples` runs them; the spec asks for about 30 s or less).
"C64 app run (s)" is the same time through the final program, as a user
gets it: F3, the example, F1, until the program ends (VICE's CPU cycle
stopwatch from the F1 key to the end of `pl0_run`, / 985248), recorded by
`tests/c64_app_examples.sh --record` in `c64-app-times.tsv`
(`make c64-app-examples` fails if any example takes more than 30 s).

| Example | Kind | Source bytes | P-code instructions | Functions | Turn trig | Lines | Extent (x; y) | C64 s | C64 app run (s) |
|---------|------|-------------:|--------------------:|----------:|----------:|------:|---------------|------:|----------------:|
"""


def budget(mode, rows_path, doc_path):
    rows = []
    with open(rows_path) as f:
        for l in f:
            if l.strip():
                rows.append(l.split())
    rows.sort()
    def read_times(fname):
        times = {}
        tpath = os.path.join(os.path.dirname(doc_path), fname)
        if os.path.exists(tpath):
            with open(tpath) as f:
                for l in f:
                    p = l.split()
                    if len(p) == 2 and not l.startswith("#"):
                        times[p[0]] = p[1]
        return times
    times = read_times("c64-times.tsv")
    app_times = read_times("c64-app-times.tsv")
    text = DOC_HEAD.format(budget=INSTR_BUDGET)
    for name, kind, nbytes, instr, fns, trig, nlines, x0, x1, y0, y1 in rows:
        ext = "%s..%s; %s..%s" % (x0, x1, y0, y1) if kind == "drawing" else "-"
        lines = nlines if kind == "drawing" else "-"
        text += "| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n" % (
            name.upper(), kind, nbytes, "{:,}".format(int(instr)), fns, trig, lines, ext,
            times.get(name, "?"), app_times.get(name, "?"))
    if mode == "write":
        with open(doc_path, "w") as f:
            f.write(text)
        return []
    try:
        with open(doc_path) as f:
            old = f.read()
    except OSError:
        old = ""
    if old != text:
        return ["%s is out of date: run tests/run_examples.sh --write-budget" % doc_path]
    return []


def main(argv):
    if len(argv) == 3 and argv[1] == "source":
        problems = check_source(argv[2])
    elif len(argv) == 5 and argv[1] == "output":
        problems = check_output(argv[2], argv[3], argv[4])
    elif len(argv) == 5 and argv[1] == "budget" and argv[2] in ("check", "write"):
        problems = budget(argv[2], argv[3], argv[4])
    else:
        print(__doc__, file=sys.stderr)
        return 2
    for p in problems:
        print("  " + p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
